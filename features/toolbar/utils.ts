import { getActionById } from "@/constants/actions";

const EXTENSION_CONTEXT_INVALIDATED_RE = /extension context invalidated/i;
const SETUP_FAILURE_RE =
  /not configured|no provider|no api key|missing api key|provider.*(required|missing)|usefloating hook|contextual-toolbar\.tsx/i;

export function createActionPrompt(
  actionId: string,
  text: string,
  customPrompt?: string
): string {
  const instruction =
    actionId === "custom-prompt"
      ? customPrompt?.trim() || "Improve this text."
      : (getActionById(actionId)?.prompt ?? "Improve this text.");

  return `Instruction: ${instruction}\n\nInput Text:\n${text}\n\nTransformed Output:\n`;
}

const PREAMBLE_HEADER_RE =
  /(?:^|\n+)(?:the (?:final )?(?:output|result|text) (?:is|will be)|here (?:is|'s) the (?:transformed|revised|rewritten)? ?(?:text|output|result)|(?:output|result|transformed text|revised text|rewritten text|final output|instruction|task|output text)):\s*/gi;

export function normalizeModelOutput(rawText: string): string {
  let cleaned = rawText.trim();
  if (!cleaned) {
    return "";
  }

  // Split by preamble markers (e.g. "The final output is:", "The output will be:", "Output:")
  const blocks = cleaned
    .split(PREAMBLE_HEADER_RE)
    .map((b) => b.trim())
    .filter(Boolean);

  if (blocks.length > 0) {
    // Deduplicate identical output blocks generated by conversational models
    const uniqueBlocks = Array.from(new Set(blocks));
    cleaned = uniqueBlocks.join("\n\n").trim();
  }

  // If the text is wrapped in quotes or triple backticks, unwrap them
  if (
    (cleaned.startsWith('"') && cleaned.endsWith('"') && cleaned.length >= 2) ||
    (cleaned.startsWith("'") && cleaned.endsWith("'") && cleaned.length >= 2)
  ) {
    cleaned = cleaned.slice(1, -1).trim();
  } else if (cleaned.startsWith("```") && cleaned.endsWith("```")) {
    cleaned = cleaned
      .replace(/^```[a-z]*\n?/i, "")
      .replace(/\n?```$/, "")
      .trim();
  }

  return cleaned;
}

export function getActionLabel(actionId: string | null): string {
  if (!actionId) {
    return "action";
  }

  if (actionId === "custom-prompt") {
    return "custom prompt";
  }

  return getActionById(actionId)?.label ?? actionId;
}

export function getFriendlyActionError(
  error: unknown,
  provider?: string
): string {
  const message = error instanceof Error ? error.message : "Unknown AI error";

  if (EXTENSION_CONTEXT_INVALIDATED_RE.test(message)) {
    return "Extension was reloaded or updated. Refresh this page, select text again, and retry.";
  }

  // Handle Transformers.js errors specifically
  if (
    provider === "transformers" ||
    message.includes("Transformers") ||
    message.includes("Hugging Face") ||
    message.includes("onnx")
  ) {
    if (
      message.includes("huggingface.co") &&
      (message.includes("Failed to fetch") || message.includes("fetch failed"))
    ) {
      return "Failed to download model from Hugging Face. Check your internet connection or Hugging Face access token.";
    }
    if (
      message.includes("model not found") ||
      message.includes("not found on Hugging Face") ||
      message.includes("404")
    ) {
      return "Model not found. Check the model ID in Dashboard > Self-Hosted > Transformers.js.";
    }
    return `In-browser model error: ${message}`;
  }

  // Handle Ollama errors specifically
  if (provider === "ollama" || message.includes("Ollama")) {
    if (/forbidden/i.test(message)) {
      return 'Ollama access forbidden: Set OLLAMA_ORIGINS="*" in your Ollama environment to allow extension requests.';
    }
    if (/model.*not found/i.test(message)) {
      return "Ollama model not found. Ensure you pulled the model (e.g. `ollama pull <model>`) or check the model name in settings.";
    }
    if (
      message.includes("ECONNREFUSED") ||
      message.includes("fetch failed") ||
      message.includes("Failed to fetch")
    ) {
      return "Ollama is not accessible. Ensure Ollama is running locally or check your Base URL & connection.";
    }
  }

  if (
    message.includes("ECONNREFUSED") ||
    message.includes("fetch failed") ||
    message.includes("Failed to fetch")
  ) {
    return "Network error: Failed to connect to AI provider. Check your network or API endpoint.";
  }

  if (SETUP_FAILURE_RE.test(message)) {
    return "No AI provider configured. Go to Dashboard > AI Providers in Options and add a provider with API key.";
  }

  return `Request failed: ${message}`;
}
